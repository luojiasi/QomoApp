from __future__ import annotations

import enum

class ProgramStep(enum.IntEnum):
    """程序执行的步骤编号"""
    # 初始化与连接
    检查控制器是否连接 = 0

    # 激光模式选择
    选择激光器模式 = 30
    发送扫黑激光模式参数 = 31
    发送工作激光模式参数 = 32

    # 激光输出使能
    打开激光器 = 40
    关闭激光器 = 41

    # 当前执行钻石步骤
    切割钻石台面 = 100
    切割钻石冠面 = 200
    切割钻石腰面 = 300
    切割钻石亭面 = 400



    # 终止
    完成分步骤 = 900
    终止任务 = 9999

