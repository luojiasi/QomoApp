"""程序执行步骤枚举"""

from __future__ import annotations

import enum


class ProgramStep(enum.IntEnum):
    """程序执行的步骤编号，语义化命名替代原有 0/10/20/... 魔术数字。"""

    # 初始化与连接
    检查控制器是否连接 = 0
    移动到起点 = 10
    等待XY轴到位_20 = 20

    # 激光模式选择
    选择激光模式 = 30
    发送扫黑激光参数 = 31
    发送工作激光参数 = 32

    # 激光输出使能
    打开激光输出 = 40
    打开R轴旋转 = 41

    # 深度检查
    检查是否到达下降深度 = 50

    # Z 轴下降
    下降Z轴到达指定位置 = 60
    等待下降Z轴到位 = 70

    # XY 运动 / 插补
    XY轴连续插补开始 = 80
    切割次数 = 81
    等待XY轴POST插入 = 82

    # 开口偏移
    更新开口偏移值 = 90

    # R 轴切圆专用
    读取R轴位置 = 90  # 与 更新开口偏移值 同值但不同上下文
    等待R轴旋转完成 = 90  # R 轴旋转等待循环

    # 降层计算
    计算下一层开口 = 100
    移动至下一层开口 = 100  # R 轴模式下的 X 移动
    检查X轴状态值 = 110

    # 4P 专用
    旋转U轴 = 12
    等待U轴旋转到位 = 13

    # 中转
    STEP_110 = 110
    STEP_120 = 120
    STEP_130 = 130
    STEP_140 = 140
    STEP_150 = 150

    # 清理
    清理所有状态 = 300
    等待Z轴回指定位置 = 301

    # 终止
    结束程序运行 = 999
    终止任务 = 9999
