def 构建执行任务的参数(数据: dict[str, Any],当前平面Z的位置, 所有高度总和: float = 0.0, 累计高度: float = 0.0 , 是否存在台面:bool = False,清晰点距离自动切台面的位置:float=0.0) -> dict[str, Any]:

    """将前端解析的行数据转换为执行任务的参数。

    等分线段：根据直径和分割数计算圆心到等分弦线的垂直距离 d = R × cos(π / N)，
    其中 R = 直径/2，N = 分割数，每条弦的距离与长度都相同。

    非等分直线：切角矩形（祖母绿 / 雷迪恩轮廓），由长、宽、切角比例确定 8 条边，
    每条边的中心距与边长各不相同，见 构建非等分直线的参数。

    曲线：一行一段。中心圆按半径+偏心等角采点；超椭圆按长/宽/n 采极径点。
    同一圈腰棱用 同层 编组，见 构建曲线的参数。
    """

    路径类型 = str(数据.get("路径类型", 等分线段路径))

    if 路径类型 == 非等分直线路径:
        return 构建非等分直线的参数(数据,累计高度,清晰点距离自动切台面的位置)
    if 路径类型 == 曲线路径:
        return 构建曲线的参数(数据,累计高度,清晰点距离自动切台面的位置)
    if 路径类型 == 等分线段路径:
        return 构建等分直线的参数(数据,累计高度,清晰点距离自动切台面的位置)
    raise ValueError(f"未知路径类型：{路径类型}")


