    这个是否为台面数据 = True if 角度 == 0 else False
    U轴的旋转角度 = 90 - (角度 + 角度补偿) if 角度 > 0 else -(-90 - (角度 + 角度补偿))
    是否反向 = False if 角度 >= 0 else True

